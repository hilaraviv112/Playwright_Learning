# ---------- 1. משתנים ----------
# משתנה = "קופסה" עם שם, ששומרת בתוכה ערך
user_name = "Hila"          # מחרוזת (str) - טקסט, תמיד בתוך מירכאות
age = 30                    # מספר שלם (int)
price = 19.90               # מספר עשרוני (float)
is_logged_in = True         # בוליאני (bool) - True או False בלבד

print("שם:", user_name)
print("סוג המשתנה age:", type(age))

# ---------- 2. if / else ----------
if is_logged_in:
    print("ברוכה הבאה,", user_name)
else:
    print("צריך להתחבר קודם")

# elif = "אחרת, אם..."
if age < 18:
    print("קטינה")
elif age < 65:
    print("בוגרת")
else:
    print("גמלאית")

# ---------- 3. רשימות (list) ----------
tasks = ["לקנות חלב", "ללמוד פייתון", "לכתוב טסט"]
print("מספר משימות:", len(tasks))   # len = אורך הרשימה
print("המשימה הראשונה:", tasks[0])  # הספירה מתחילה מ-0!
tasks.append("לשתות מים")           # הוספה לסוף הרשימה

# ---------- 4. לולאה (for) ----------
for task in tasks:
    print("-", task)

# ---------- 5. פונקציות ----------
# פונקציה = חתיכת קוד עם שם, שמקבלת קלט ומחזירה תוצאה
def add(a, b):
    return a + b

result = add(2, 3)
print("2 + 3 =", result)

# ---------- 6. assert - הלב של הבדיקות! ----------
# assert בודק שמשהו נכון. אם הוא נכון - לא קורה כלום.
# אם הוא לא נכון - התוכנית נעצרת עם שגיאה (= הטסט נכשל).
assert add(2, 3) == 5          # עובר בשקט
assert len(tasks) == 4         # עובר בשקט
print("כל הבדיקות עברו ✅")

